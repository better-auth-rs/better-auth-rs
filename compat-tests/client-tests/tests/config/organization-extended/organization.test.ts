compatScenario("multi-team invitations preserve every team identity without selecting an active team", async (ctx) => {
  await signUpUser(ctx, "owner", "multi-team-owner", "Owner");
  const member = await signUpUser(ctx, "member", "multi-team-member", "Member");
  const { call, observations } = requests(ctx);
  const org = asRecord(await call("owner", "create", { name: "Multi Team Organization", slug: ctx.uniqueToken("multi-team") }));
  const organizationId = org.id;
  const first = asRecord(await call("owner", "create-team", { organizationId, name: "First Team" }));
  const second = asRecord(await call("owner", "create-team", { organizationId, name: "Second Team" }));
  const teamIds = [first.id, second.id];
  const invitation = asRecord(await call("owner", "invite-member", { organizationId, teamId: teamIds, email: member.email, role: "member" }));
  expect(typeof invitation.teamId).toBe("string");
  expect((invitation.teamId as string).split(",")).toEqual(teamIds);
  const accepted = asRecord(await call("member", "accept-invitation", { invitationId: invitation.id }));
  expect(asRecord(accepted.invitation).teamId).toBe(invitation.teamId);
  expect(asRecord(accepted.member).userId).toBe(member.signup.data!.user.id);
  expect(asRecord(accepted.member).organizationId).toBe(organizationId);
  const membershipIds = [];
  for (const teamId of teamIds) {
    const memberships = asArray(await call("member", `list-team-members?teamId=${teamId}`));
    expect(memberships).toHaveLength(1);
    const membership = asRecord(memberships[0]);
    expect(membership.teamId).toBe(teamId);
    expect(membership.userId).toBe(member.signup.data!.user.id);
    membershipIds.push(membership.id);
  }
  expect(membershipIds[0]).not.toBe(membershipIds[1]);
  const teams = asArray(await call("member", "list-user-teams"));
  expect(teams.map((team) => asRecord(team).id)).toEqual(teamIds);
  const session = await member.client.getSession();
  expect(asRecord(session.data!.session).activeTeamId).toBeNull();
  expect(asRecord(session.data!.session).activeOrganizationId).toBe(organizationId);
  observations.push(session);
  return observations;
});
